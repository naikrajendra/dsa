package com.hackerrank.warmup;

import java.io.*;
import java.util.*;

/**
 * HackerRank Warmup Problem
 * Solve Me First
 */
public class SolveMe {

    public static void main(String[] args) {
        Scanner scan = new Scanner(System.in);

        // Read first number
        int a = scan.nextInt();

        // Read second number
        int b = scan.nextInt();

        // Output
        System.out.println(a + b);

        scan.close();
    }

}
